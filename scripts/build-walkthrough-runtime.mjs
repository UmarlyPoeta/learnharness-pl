// Bundles src/core/walkthrough/runtime-entry.ts into a string constant
// (src/core/walkthrough/runtime-bundle.ts) the walkthrough document inlines.
// Run: npm run build:walkthrough
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(root, "src/core/walkthrough/runtime-bundle.ts");

export async function buildRuntimeSource() {
	const result = await build({
		entryPoints: [path.join(root, "src/core/walkthrough/runtime-entry.ts")],
		bundle: true,
		format: "iife",
		minify: true,
		target: "es2019",
		write: false,
		logLevel: "silent",
	});
	return result.outputFiles[0].text.trim();
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const js = await buildRuntimeSource();
	writeFileSync(
		OUT,
		`// GENERATED by scripts/build-walkthrough-runtime.mjs — do not edit\nexport const WALKTHROUGH_RUNTIME_JS: string = ${JSON.stringify(js)};\n`,
	);
	console.log(`wrote ${path.relative(root, OUT)} (${js.length} chars)`);
}
